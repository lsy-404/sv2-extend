"""Validate witnessed task/callback phases, not only process liveness."""
def validate(report):
    v=report['result'];a=v['allowed'];z=v['blocked'];l=v['live'];x=v['restored'];c=v['completionBlock'];i=v['delegateInheritance']
    return {
        'hostAlive':report['hostAlive'],
        'blockedNoServerRequest':'/background-blocked' not in report['hits'],
        'allowedReachedServer':'/background-allowed' in report['hits'],
        'restoredReachedServer':'/background-restored' in report['hits'],
        'liveReachedServer':'/background-live' in report['hits'],
        'genuineBackgroundConfigurations':all(v[k]['configurationHasIdentifier'] for k in ['allowed','blocked','live','restored']),
        'blockedCancelled':z['error']==-999 and z['completed'],
        'blockedNoDownload':not z['downloaded'] and z['receivedBytes']==0,
        'allowedDownloaded':a['downloaded'] and a['error']==0 and a['receivedBytes']==15,
        'restoredDownloaded':x['downloaded'] and x['error']==0 and x['receivedBytes']==15,
        'liveProgressObserved':l['hadProgress'],
        'liveWasRunningAtBlock':l['wasRunningAtBlock'],
        'liveCancelled':l['error']==-999 and l['completed'],
        'liveNotPublishedAsDownload':not l['downloaded'],
        'serverObservedPeerClose':any(report['livePeerClosed']),
        'liveBodyNotFullySent':bool(report['liveBytesWritten']) and all(n<8*1024*1024 for n in report['liveBytesWritten']),
        'delegateHeld':l['completionHeld'],
        'nativeTaskAlreadyCompleted':l['taskStateAtBarrier']==3,
        'delegatePendingCount':l['callbacksPendingAtBarrier']>=1,
        'delegateNotPrematurelyDrained':not l['drainedWithDelegateHeld'],
        'delegateReleasedCountZero':l['callbacksPendingAfter']==0,
        'sessionsInvalidated':all(v[k]['invalidated'] for k in ['allowed','blocked','live','restored']),
        'blockQueuedPending':c['queuedPending']>=1,
        'blockQueuedNotDrained':not c['drainedWhileQueued'],
        'blockExecutingPending':c['executingPending']>=1,
        'blockExecutingNotDrained':not c['drainedWhileExecuting'],
        'blockReturnedCountZero':c['returned'] and c['remainingPending']==0,
        'blockDataPreserved':c['bodyValid'] and c['entered'],
        'inheritanceParentReturned':i['superReturned'],
        'inheritanceStillPending':i['pendingAfterSuper']>=1 and not i['drainedBeforeDerivedReturns'],
        'inheritanceFinallyCleared':i['pendingAfterDerivedReturns']==0 and i['downloaded'] and i['invalidated'],
        'forwardingDelegatePreserved':v['forwardingDelegate']['originalDelegatePreserved'],
        'forwardingSessionInvalidated':v['forwardingDelegate']['invalidated'],
        'forwardingCoverageConservative':v['forwardingDelegate']['coverageRemainsConservative'],
    }
